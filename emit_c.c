#include "emit_c.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Write a C string-literal-safe version of str to fp */
static void emit_escaped(FILE* fp, const char* str) {
    for (const char* p = str; *p; p++) {
        if (*p == '"')  { fputc('\\', fp); fputc('"',  fp); }
        else if (*p == '\\') { fputc('\\', fp); fputc('\\', fp); }
        else fputc(*p, fp);
    }
}

int emit_c(DFA* dfa, Rule* rules, int rule_count,
           const char* out_path, const char* rules_file) {
    FILE* fp = fopen(out_path, "w");
    if (!fp) { perror("emit_c: fopen"); return -1; }

    int n = dfa->num_states;
    int r = rule_count;

    /* ---- header comment + includes ---- */
    fprintf(fp, "/* Generated by MiniLex from %s */\n",
            rules_file ? rules_file : "<unknown>");
    fputs("#include <stdio.h>\n", fp);
    fputs("#include <stdlib.h>\n", fp);
    fputs("#include <string.h>\n", fp);
    fputs("#include <ctype.h>\n", fp);
    fputs("#include <sys/stat.h>\n\n", fp);

    fprintf(fp, "#define ML_NUM_STATES %d\n", n);
    fprintf(fp, "#define ML_NUM_RULES  %d\n\n", r);

    /* ---- transition table ---- */
    fputs("/* ml_trans[state][char]: next state, or -1 for dead */\n", fp);
    fputs("static const int ml_trans[ML_NUM_STATES][256] = {\n", fp);
    for (int i = 0; i < n; i++) {
        fputs("  {", fp);
        for (int c = 0; c < 256; c++) {
            DFAState* t = dfa->states[i]->transitions[c];
            fprintf(fp, "%d", t ? t->id : -1);
            if (c < 255) fputc(',', fp);
        }
        fprintf(fp, "}%s\n", i < n - 1 ? "," : "");
    }
    fputs("};\n\n", fp);

    /* ---- accept table ---- */
    fputs("/* ml_accept[state]: 0=not accepting, >0=rule_id */\n", fp);
    fputs("static const int ml_accept[ML_NUM_STATES] = {", fp);
    for (int i = 0; i < n; i++) {
        fprintf(fp, "%d", dfa->states[i]->accept_rule_id);
        if (i < n - 1) fputc(',', fp);
    }
    fputs("};\n\n", fp);

    /* ---- rule name table (index 0 unused) ---- */
    fputs("static const char* const ml_names[ML_NUM_RULES + 1] = {\n  \"\"", fp);
    for (int i = 0; i < r; i++) {
        fputs(",\n  \"", fp);
        emit_escaped(fp, rules[i].name);
        fputc('"', fp);
    }
    fputs("\n};\n\n", fp);

    /* ---- skip flags table (index 0 unused) ---- */
    fputs("static const int ml_skip[ML_NUM_RULES + 1] = {0", fp);
    for (int i = 0; i < r; i++) fprintf(fp, ",%d", rules[i].skip);
    fputs("};\n\n", fp);

    /* ---- palindrome flags table (index 0 unused) ---- */
    fputs("static const int ml_palindrome[ML_NUM_RULES + 1] = {0", fp);
    for (int i = 0; i < r; i++) fprintf(fp, ",%d", rules[i].palindrome);
    fputs("};\n\n", fp);

    /* ---- semantic palindrome helper ---- */
    fputs("static int ml_is_palindrome(const char* text, int len) {\n", fp);
    fputs("  for (int left = 0, right = len - 1; left < right; left++, right--)\n", fp);
    fputs("    if (text[left] != text[right]) return 0;\n", fp);
    fputs("  return 1;\n", fp);
    fputs("}\n\n", fp);

    /* ---- ml_read_file helper ---- */
    fputs("static char* ml_read_file(const char* path) {\n", fp);
    fputs("  struct stat st;\n", fp);
    fputs("  if (stat(path, &st) != 0 || !S_ISREG(st.st_mode)) return NULL;\n", fp);
    fputs("  FILE* f = fopen(path, \"rb\");\n", fp);
    fputs("  if (!f) return NULL;\n", fp);
    fputs("  if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return NULL; }\n", fp);
    fputs("  long sz = ftell(f);\n", fp);
    fputs("  if (sz < 0) { fclose(f); return NULL; }\n", fp);
    fputs("  if (fseek(f, 0, SEEK_SET) != 0) { fclose(f); return NULL; }\n", fp);
    fputs("  char* buf = malloc((size_t)sz + 1);\n", fp);
    fputs("  if (!buf) { fclose(f); return NULL; }\n", fp);
    fputs("  size_t rd = fread(buf, 1, (size_t)sz, f);\n", fp);
    fputs("  if (rd != (size_t)sz && ferror(f)) { free(buf); fclose(f); return NULL; }\n", fp);
    fputs("  buf[rd] = '\\0';\n", fp);
    fputs("  fclose(f);\n", fp);
    fputs("  return buf;\n", fp);
    fputs("}\n\n", fp);

    /* ---- ml_tokenize: maximal-munch driver (mirrors tokenizer.c logic) ---- */
    fputs("static int ml_tokenize(const char* input, int show_skipped,\n", fp);
    fputs("                        int print_positions) {\n", fp);
    fputs("  int input_len = (int)strlen(input);\n", fp);
    fputs("  int pos = 0, has_error = 0, line = 1, col = 1;\n", fp);
    fputs("  while (pos < input_len) {\n", fp);
    fputs("    int state = 0; /* start state is always state 0 */\n", fp);
    fputs("    int lookahead = pos;\n", fp);
    fputs("    int last_accept_pos = -1, last_accept_rule = 0;\n", fp);
    fputs("    if (ml_accept[state] > 0) {\n", fp);
    fputs("      last_accept_pos = pos; last_accept_rule = ml_accept[state];\n", fp);
    fputs("    }\n", fp);
    fputs("    while (lookahead < input_len) {\n", fp);
    fputs("      int c = (unsigned char)input[lookahead];\n", fp);
    fputs("      int next = ml_trans[state][c];\n", fp);
    fputs("      if (next < 0) break;\n", fp);
    fputs("      lookahead++; state = next;\n", fp);
    fputs("      if (ml_accept[state] > 0) {\n", fp);
    fputs("        last_accept_pos = lookahead; last_accept_rule = ml_accept[state];\n", fp);
    fputs("      }\n", fp);
    fputs("    }\n", fp);
    fputs("    if (last_accept_rule > 0 && last_accept_pos > pos) {\n", fp);
    fputs("      int is_skip = (last_accept_rule <= ML_NUM_RULES)\n", fp);
    fputs("                    ? ml_skip[last_accept_rule] : 0;\n", fp);
    fputs("      int check_palindrome = (last_accept_rule <= ML_NUM_RULES)\n", fp);
    fputs("                             ? ml_palindrome[last_accept_rule] : 0;\n", fp);
    fputs("      const char* name = (last_accept_rule <= ML_NUM_RULES)\n", fp);
    fputs("                         ? ml_names[last_accept_rule] : \"UNKNOWN\";\n", fp);
    fputs("      int len = last_accept_pos - pos;\n", fp);
    fputs("      if (check_palindrome)\n", fp);
    fputs("        name = ml_is_palindrome(input + pos, len)\n", fp);
    fputs("                 ? \"PALINDROME\" : \"NOT_PALINDROME\";\n", fp);
    fputs("      int tok_line = line, tok_col = col;\n", fp);
    fputs("      for (int i = 0; i < len; i++) {\n", fp);
    fputs("        if (input[pos+i] == '\\n') { line++; col = 1; } else { col++; }\n", fp);
    fputs("      }\n", fp);
    fputs("      if (!is_skip || show_skipped) {\n", fp);
    /* printf("[%s \"", name);  — note: \" in format = literal " in output */
    fputs("        printf(\"[%s \\\"\", name);\n", fp);
    fputs("        for (int i = 0; i < len; i++) {\n", fp);
    fputs("          char ch = input[pos+i];\n", fp);
    fputs("          if (ch == '\\n') printf(\"\\\\n\");\n", fp);
    fputs("          else if (ch == '\\t') printf(\"\\\\t\");\n", fp);
    fputs("          else if (ch == '\\r') printf(\"\\\\r\");\n", fp);
    /* else if (ch == '"') printf("\\\"");  — prints backslash-quote */
    fputs("          else if (ch == '\"') printf(\"\\\\\\\"\");\n", fp);
    fputs("          else printf(\"%c\", ch);\n", fp);
    fputs("        }\n", fp);
    /* if (print_positions) printf("\" %d:%d]\n", tok_line, tok_col); */
    fputs("        if (print_positions) printf(\"\\\" %d:%d]\\n\", tok_line, tok_col);\n", fp);
    /* else printf("\"]\n"); */
    fputs("        else printf(\"\\\"]\\n\");\n", fp);
    fputs("      }\n", fp);
    fputs("      pos = last_accept_pos;\n", fp);
    fputs("    } else {\n", fp);
    fputs("      fflush(stdout);\n", fp);
    fputs("      unsigned char err_c = (unsigned char)input[pos];\n", fp);
    fputs("      if (isprint(err_c))\n", fp);
    /* fprintf(stderr, "Lexical error at position %d (line %d, col %d): unexpected character '%c'\n", ...) */
    fputs("        fprintf(stderr,\n", fp);
    fputs("          \"Lexical error at position %d (line %d, col %d): \"\n", fp);
    fputs("          \"unexpected character '%c'\\n\",\n", fp);
    fputs("          pos, line, col, err_c);\n", fp);
    fputs("      else\n", fp);
    /* fprintf(stderr, "... unexpected character '\\x%02x'\n", ...) */
    fputs("        fprintf(stderr,\n", fp);
    fputs("          \"Lexical error at position %d (line %d, col %d): \"\n", fp);
    fputs("          \"unexpected character '\\\\x%02x'\\n\",\n", fp);
    fputs("          pos, line, col, err_c);\n", fp);
    fputs("      fflush(stderr);\n", fp);
    fputs("      has_error = 1;\n", fp);
    fputs("      if (err_c == '\\n') { line++; col = 1; } else { col++; }\n", fp);
    fputs("      pos++;\n", fp);
    fputs("    }\n", fp);
    fputs("  }\n", fp);
    fputs("  return has_error ? 1 : 0;\n", fp);
    fputs("}\n\n", fp);

    /* ---- main ---- */
    fputs("int main(int argc, char** argv) {\n", fp);
    fputs("  const char* input_arg = NULL;\n", fp);
    fputs("  int force_string = 0, show_skipped = 0, print_positions = 0;\n", fp);
    fputs("  for (int i = 1; i < argc; i++) {\n", fp);
    fputs("    if (strcmp(argv[i], \"-s\") == 0 ||\n", fp);
    fputs("        strcmp(argv[i], \"--string\") == 0)\n", fp);
    fputs("      force_string = 1;\n", fp);
    fputs("    else if (strcmp(argv[i], \"--show-skipped\") == 0)\n", fp);
    fputs("      show_skipped = 1;\n", fp);
    fputs("    else if (strcmp(argv[i], \"--positions\") == 0)\n", fp);
    fputs("      print_positions = 1;\n", fp);
    fputs("    else if (!input_arg)\n", fp);
    fputs("      input_arg = argv[i];\n", fp);
    fputs("    else {\n", fp);
    fputs("      fprintf(stderr,\n", fp);
    fputs("        \"Usage: %s [-s|--string] [--show-skipped] [--positions] <input>\\n\",\n", fp);
    fputs("        argv[0]);\n", fp);
    fputs("      return 1;\n", fp);
    fputs("    }\n", fp);
    fputs("  }\n", fp);
    fputs("  if (!input_arg) {\n", fp);
    fputs("    fprintf(stderr,\n", fp);
    fputs("      \"Usage: %s [-s|--string] [--show-skipped] [--positions] <input>\\n\",\n", fp);
    fputs("      argv[0]);\n", fp);
    fputs("    return 1;\n", fp);
    fputs("  }\n", fp);
    fputs("  char* input_str = NULL;\n", fp);
    fputs("  if (!force_string) input_str = ml_read_file(input_arg);\n", fp);
    fputs("  if (!input_str) input_str = strdup(input_arg);\n", fp);
    fputs("  if (!input_str) {\n", fp);
    fputs("    fprintf(stderr, \"Failed to allocate memory.\\n\");\n", fp);
    fputs("    return 1;\n", fp);
    fputs("  }\n", fp);
    fputs("  int ret = ml_tokenize(input_str, show_skipped, print_positions);\n", fp);
    fputs("  free(input_str);\n", fp);
    fputs("  return ret;\n", fp);
    fputs("}\n", fp);

    fclose(fp);
    return 0;
}
